const speakers: Record<string, string> = { yuki: 'ユキ', ren: 'レン', miya: 'ミヤ', sora: 'ソラ', ghost: '記録の番人' }
export function withOfficialJapanese(node: StoryNode): StoryNode {
  const translation = lines[node.id]
  if (!translation) return node
  const source = String(node.data.text || (Array.isArray(node.data.choices) ? node.data.choices.join('\n') : ''))
  const ja = { ...(Array.isArray(translation) ? { choices: translation } : { text: translation }), speaker: speakers[String(node.data.role)] || '', sourceHash: voiceTextHash(source) }
  return { ...node, data: { ...node.data, localizations: { ja } } }
}
