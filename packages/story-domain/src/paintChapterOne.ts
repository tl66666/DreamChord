const nodes: StoryNode[] = [], edges: StoryEdge[] = []
const titles = ['两个人记得的事', '六月六日', '炉前的一页', '第二班车', '重新问一次']
let scene = 1, previous: string | undefined
function add(short: string, type: StoryNodeType, data: Record<string, unknown>) {
  const id = `pc1-${short}`
  nodes.push({ id, type, position: { x: scene * 480, y: nodes.length * 110 }, data: { ...data, sceneGroupId: `paint-ch1-scene-${scene}`, sceneTitle: titles[scene - 1], sceneCode: `2-${scene}` } })
  if (previous) edges.push({ id: `${previous}-${id}`, source: previous, target: id, animated: true })
  previous = id
  return id
}
function n(id: string, zh: string, ja: string, extra: Record<string, unknown> = {}) {
  return add(id, 'subtitle', { role: '旁白', text: zh, localizations: { ja: { text: ja, sourceHash: voiceTextHash(zh) } }, ...extra })
}
function l(...ids: string[]) {
  for (const id of ids) {
    const line = PAINT_CHAPTER_ONE_LINES.find(v => v.id === `pc1-${id}`)
    if (!line) throw new Error(`Missing chapter-one line: ${id}`)
    const { role, text, ja, emotion } = line
    add(id, 'dialogue', { role, text,
      voiceDirection: directVoiceLine({ role, text, overrides: { emotion: emotion === 'serious' ? 'tense' : 'neutral', intensity: emotion === 'serious' ? .35 : .25, pace: .98 } }),
      localizations: { ja: { text: ja, sourceHash: voiceTextHash(text) } },
      voiceTracks: { ja: { url: `/assets/audio/paint-chapter-one/pc1-${id}-ja.ogg`, textHash: voiceTextHash(ja), profileId: `paint-voice-${slugs[role]}` } },
    })
  }
}
function bg(id: string, name: string, old = false) { add(id, 'background', { backgroundId: `${old ? oldArt : art}/${name}.webp` }) }
function show(id: string, role: Role, expression: 'normal' | 'smile' | 'serious', position: 'left' | 'right' | 'center', action = 'show') { add(id, 'character', { characterId: role, expression, position, action }) }
